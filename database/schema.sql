CREATE DATABASE IF NOT EXISTS cuidar_juntos CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cuidar_juntos;

CREATE TABLE IF NOT EXISTS USUARIO (
  id_usuario INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  perfil ENUM('ADMIN','COLABORADOR') NOT NULL,
  status ENUM('ATIVO','INATIVO') NOT NULL DEFAULT 'ATIVO',
  tentativas_falhas INT UNSIGNED NOT NULL DEFAULT 0,
  bloqueado_ate DATETIME NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS PESSOA_ASSISTIDA (
  id_pessoa INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(120) NOT NULL,
  data_nascimento DATE NULL,
  consentimento_registrado TINYINT(1) NOT NULL DEFAULT 0,
  data_consentimento DATETIME NULL,
  status ENUM('ATIVO','INATIVO') NOT NULL DEFAULT 'ATIVO',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS USUARIO_PESSOA (
  id_usuario INT UNSIGNED NOT NULL,
  id_pessoa INT UNSIGNED NOT NULL,
  pode_registrar_administracao TINYINT(1) NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id_usuario, id_pessoa),
  CONSTRAINT fk_up_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario),
  CONSTRAINT fk_up_pessoa FOREIGN KEY (id_pessoa) REFERENCES PESSOA_ASSISTIDA(id_pessoa)
);

CREATE TABLE IF NOT EXISTS ATIVIDADE (
  id_atividade INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  id_pessoa INT UNSIGNED NOT NULL,
  titulo VARCHAR(150) NOT NULL,
  descricao TEXT NULL,
  data_hora DATETIME NULL,
  status ENUM('PENDENTE','ASSUMIDA','CONCLUIDA','CANCELADA') NOT NULL DEFAULT 'PENDENTE',
  criado_por INT UNSIGNED NOT NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_at_pessoa FOREIGN KEY (id_pessoa) REFERENCES PESSOA_ASSISTIDA(id_pessoa),
  CONSTRAINT fk_at_usuario FOREIGN KEY (criado_por) REFERENCES USUARIO(id_usuario)
);

CREATE TABLE IF NOT EXISTS HISTORICO (
  id_historico BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  id_usuario INT UNSIGNED NOT NULL,
  acao VARCHAR(40) NOT NULL,
  entidade VARCHAR(40) NOT NULL,
  id_registro INT UNSIGNED NOT NULL,
  data_hora DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  detalhes VARCHAR(255) NULL,
  CONSTRAINT fk_hist_usuario FOREIGN KEY (id_usuario) REFERENCES USUARIO(id_usuario)
);
